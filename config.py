# ------------------------------------------------------------
# 1. Excel의 열 이름 설정
# ------------------------------------------------------------
# 실제 Excel에서 사용하는 열 이름과 정확하게 일치해야 합니다.
#
# 예를 들어 Excel에
# "차량고유번호"
# "차량종류"
# "최근엔진오일교체일"
# "최근교체시주행거리"
# "현재총주행거리"
# 라는 열이 있다면 아래와 같이 설정합니다.
# ------------------------------------------------------------

COLUMN_VEHICLE_ID = "차량고유번호"
COLUMN_VEHICLE_TYPE = "차량종류"

COLUMN_OIL_CHANGE_DATE = "최근엔진오일교체일"
COLUMN_OIL_CHANGE_MILEAGE = "최근교체시주행거리"
COLUMN_CURRENT_MILEAGE = "현재총주행거리"


# ------------------------------------------------------------
# 2. Excel 파일의 Sheet 이름
# ------------------------------------------------------------
# 첫 번째 Sheet를 사용할 경우 0
#
# 특정 Sheet를 사용할 경우:
# SHEET_NAME = "차량정보"
# ------------------------------------------------------------

SHEET_NAME = 0


# ------------------------------------------------------------
# 3. 차량 종류별 엔진오일 교체 주기
# ------------------------------------------------------------
# 단위: km
#
# 예:
# A 차량 → 5000km
# B 차량 → 7000km
# C 차량 → 10000km
#
# 차량 종류가 추가되면 여기에 추가하면 됩니다.
# ------------------------------------------------------------

OIL_CHANGE_INTERVAL = {
    "A": 5000,
    "B": 7000,
    "C": 10000,
}


# ------------------------------------------------------------
# 4. 엔진오일 상태 분류 기준
# ------------------------------------------------------------
#
# 예를 들어 A 차량의 교체주기가 5000km이고
# 현재까지 4800km를 주행했다면
#
# 5000 - 4800 = 200km
#
# 즉, 교체주기까지 200km 남은 상태입니다.
#
# 아래 설정에서:
#
# REMAINING_WARNING_KM = 500
#
# 이면
#
# 남은 거리가 500km 이하 → "교체주기 임박"
#
# ------------------------------------------------------------

REMAINING_WARNING_KM = 500


# ------------------------------------------------------------
# 5. 교체 필요 기준
# ------------------------------------------------------------
#
# 교체주기에 도달했거나 초과한 경우
# "교체 필요" 또는 "교체 시급"으로 분류합니다.
#
# OVERDUE_URGENT_KM = 500
#
# 의미:
#
# 기준보다 0~499km 초과
#     → 교체 필요
#
# 기준보다 500km 이상 초과
#     → 교체 시급
#
# ------------------------------------------------------------

OVERDUE_URGENT_KM = 500


# ------------------------------------------------------------
# 6. 결과 Excel 파일 이름
# ------------------------------------------------------------

OUTPUT_FILE = "차량관리_결과.xlsx"
