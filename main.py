# 차량 종류와 교체 기준 등이 저장된 설정 파일
import config
from excel_manager import (
    get_input_file,
    load_excel,
    validate_columns,
    clean_numeric_data
)

from analyzer import (
    calculate_oil_mileage,
    classify_all_vehicles,
    calculate_vehicle_type_statistics
)


# ============================================================
# 함수 9. 콘솔에 결과 출력
# ============================================================

def print_statistics(statistics_df):
    """
    차량 종류별 통계 결과를
    콘솔창에 표 형태로 출력합니다.
    """

    print("\n")
    print("=" * 70)
    print("차량 종류별 관리 현황")
    print("=" * 70)

    # pandas DataFrame을 콘솔에 출력
    #
    # index=False
    # → 왼쪽에 0, 1, 2 등의 번호가 나오지 않게 함
    #
    # formatters
    # → 비율을 소수점 둘째 자리까지 표시
    # --------------------------------------------------------

    print(
        statistics_df.to_string(
            index=False,
            formatters={
                "비율(%)": lambda x: f"{x:.2f}"
            }
        )
    )

    print("=" * 70)


# ============================================================
# main함수: 프로그램 전체 실행
# ============================================================

def main():

    print("=" * 70)
    print("군용 차량 관리 프로그램")
    print("=" * 70)

    # --------------------------------------------------------
    # 1. 사용자가 Excel 파일 선택
    # --------------------------------------------------------

    input_file = get_input_file()
    
    # --------------------------------------------------------
    # 2. Excel 파일 읽기
    # --------------------------------------------------------

    df = load_excel(input_file)

    # --------------------------------------------------------
    # 3. Excel의 열 구조 확인
    # --------------------------------------------------------

    validate_columns(df)

    # --------------------------------------------------------
    # 4. 숫자 데이터 정리
    # --------------------------------------------------------

    df = clean_numeric_data(df)

    # --------------------------------------------------------
    # 5. 엔진오일 교체 후 주행거리 계산
    # --------------------------------------------------------

    df = calculate_oil_mileage(df)

    # --------------------------------------------------------
    # 6. 모든 차량의 엔진오일 상태 계산
    # --------------------------------------------------------

    df = classify_all_vehicles(df)

    # --------------------------------------------------------
    # 7. 차량 종류별 통계 계산
    # --------------------------------------------------------

    statistics_df = (
        calculate_vehicle_type_statistics(df)
    )

    # --------------------------------------------------------
    # 8. 콘솔창에 결과 출력
    # --------------------------------------------------------

    print_statistics(
        statistics_df
    )

    print("\n프로그램 실행이 완료되었습니다.")


# ============================================================
# 프로그램 시작점
# ============================================================

if __name__ == "__main__":
    main()
